async function executeRequestedTool(toolName, args, event, keys) {
  event.reply('tool-executed', `Waiting for permission to run tool: \`${toolName}\`...`);
  const allowed = await askUserPermission(event, toolName, args);
  if (!allowed) {
    event.reply('tool-executed', `Permission Denied by user.`);
    return "Permission denied. The user rejected running this action.";
  }

  event.reply('tool-executed', `Permission Granted! Running action...`);
  let executionResult = '';
  
  try {
    if (toolName === 'execute_command') {
      const cmd = args.command;
      event.reply('tool-executed', `Running PowerShell command: \`${cmd}\`...`);
      executionResult = await new Promise((resolve) => {
        exec(cmd, { shell: 'powershell.exe' }, (error, stdout, stderr) => {
          if (error) {
            resolve(`Error: ${error.message}\nStderr: ${stderr}`);
          } else {
            resolve(stdout || stderr || 'Command executed successfully.');
          }
        });
      });
      event.reply('tool-executed', `Command output:\n${executionResult}`);
    } 
    else if (toolName === 'generate_image') {
      const prompt = args.prompt;
      event.reply('tool-executed', `Generating image via Imagen 3...`);
      const geminiKey = keys.gemini || process.env.GEMINI_API_KEY || '';
      const ai = new GoogleGenAI({ apiKey: geminiKey });
      const imgResponse = await ai.models.generateImages({
        model: 'imagen-3.0-generate-002',
        prompt: prompt,
        config: { numberOfImages: 1, aspectRatio: '1:1' }
      });

      if (imgResponse?.generatedImages?.length > 0) {
        const imageBytesBase64 = imgResponse.generatedImages[0].image.imageBytes;
        const desktopPath = path.join(process.env.USERPROFILE || '', 'Desktop');
        const fileName = `EduAI_Image_${Date.now()}.png`;
        const filePath = path.join(desktopPath, fileName);
        fs.writeFileSync(filePath, Buffer.from(imageBytesBase64, 'base64'));
        executionResult = `Image generated successfully and saved to Desktop as: ${fileName}`;
        event.reply('chat-chunk', `\n\n![Generated Image](data:image/png;base64,${imageBytesBase64})\n\n*(Saved to Desktop as ${fileName})*\n`);
        event.reply('tool-executed', executionResult);
      } else {
        throw new Error("No image generated by the Imagen API.");
      }
    }
    else if (toolName === 'send_whatsapp_message') {
      const { phone, message } = args;
      const formattedPhone = phone.replace(/[^0-9]/g, '');
      const waUrl = `https://wa.me/${formattedPhone}?text=${encodeURIComponent(message)}`;
      event.reply('tool-executed', `Opening WhatsApp portal...`);
      executionResult = await new Promise((resolve) => {
        exec(`Start-Process "${waUrl}"`, { shell: 'powershell.exe' }, (error, stdout, stderr) => {
          if (error) resolve(`Error opening WhatsApp link: ${error.message}`);
          else resolve("Opened WhatsApp messaging tab successfully.");
        });
      });
      event.reply('tool-executed', executionResult);
    }
    else if (toolName === 'open_instagram_chat') {
      const { username } = args;
      const instaUrl = `https://www.instagram.com/${username.replace('@', '')}/`;
      event.reply('tool-executed', `Opening Instagram profile...`);
      executionResult = await new Promise((resolve) => {
        exec(`Start-Process "${instaUrl}"`, { shell: 'powershell.exe' }, (error, stdout, stderr) => {
          if (error) resolve(`Error opening Instagram link: ${error.message}`);
          else resolve(`Opened Instagram profile for ${username}.`);
        });
      });
      event.reply('tool-executed', executionResult);
    }
  } catch (err) {
    executionResult = `Execution error: ${err.message || err}`;
    event.reply('tool-executed', executionResult);
  }
  
  return executionResult;
}


async function getOllamaModel(url, configuredModel) {
  const baseUrl = url.endsWith('/api/chat') ? url.replace('/api/chat', '') : url;
  let response;
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 2000);
    response = await fetch(`${baseUrl}/api/tags`, { signal: controller.signal });
    clearTimeout(timeoutId);
  } catch (err) {
    throw new Error(`Ollama server is offline at ${baseUrl}. Make sure Ollama is running. (Reason: ${err.message})`);
  }
  
  if (!response.ok) {
    throw new Error(`Ollama API tags request failed (HTTP ${response.status})`);
  }
  
  const data = await response.json();
  const models = data.models || [];
  
  if (models.length === 0) {
    throw new Error("Ollama server is running, but no models are installed. Please run 'ollama pull qwen3.5' in your terminal.");
  }
  
  const configuredName = configuredModel ? configuredModel.toLowerCase() : '';
  const match = models.find(m => m.name.toLowerCase() === configuredName || m.name.toLowerCase().startsWith(configuredName + ':'));
  
  if (match) {
    return match.name;
  }
  
  return models[0].name;
}

