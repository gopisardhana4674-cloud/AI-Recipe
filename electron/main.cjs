// Interactive User Permission Loop Registry
const pendingPermissions = new Map();

ipcMain.on('respond-permission', (event, { id, allowed }) => {
  if (pendingPermissions.has(id)) {
    const resolve = pendingPermissions.get(id);
    resolve(allowed);
    pendingPermissions.delete(id);
  }
});

function askUserPermission(event, toolName, args) {
  const id = Math.random().toString(36).substring(2) + Date.now().toString(36);
  return new Promise((resolve) => {
    pendingPermissions.set(id, resolve);
    event.reply('confirm-action', { id, toolName, args });
  });
}

// SSE stream reader for other providers
async function handleSSEStream(response, provider, event) {
  const reader = response.body;
  if (!reader) {
    throw new Error("No response body available for streaming");
  }

  for await (const chunk of reader) {
    const text = chunk.toString();
    const lines = text.split('\n');
    for (const line of lines) {
      const cleanLine = line.trim();
      if (!cleanLine) continue;

      if (provider === 'openai' || provider === 'openrouter') {
        if (cleanLine.startsWith('data: ')) {
          const dataStr = cleanLine.substring(6);
          if (dataStr === '[DONE]') continue;
          try {
            const parsed = JSON.parse(dataStr);
            const content = parsed.choices?.[0]?.delta?.content;
            if (content) {
              event.reply('chat-chunk', content);
            }
          } catch (e) {}
        }
      } 
      else if (provider === 'anthropic') {
        if (cleanLine.startsWith('data: ')) {
          const dataStr = cleanLine.substring(6);
          try {
            const parsed = JSON.parse(dataStr);
            if (parsed.type === 'content_block_delta' && parsed.delta?.text) {
              event.reply('chat-chunk', parsed.delta.text);
            }
          } catch (e) {}
        }
      }
      else if (provider === 'ollama') {
        try {
          const parsed = JSON.parse(cleanLine);
          if (parsed.message?.content) {
            event.reply('chat-chunk', parsed.message.content);
          }
        } catch (e) {}
      }
    }
  }
}

// Provider Connectivity Testing
ipcMain.handle('test-provider', async (event, { provider, keys }) => {
  const providerInfo = providersConfig.providers[provider];
  if (!providerInfo) {
    return { success: false, error: 'Unknown provider' };
  }

  let activeKey = '';
  if (provider === 'gemini') {
    activeKey = keys.gemini || process.env.GEMINI_API_KEY || '';
  } else if (provider === 'openai') {
    activeKey = keys.openai || process.env.OPENAI_API_KEY;
  } else if (provider === 'anthropic') {
    activeKey = keys.anthropic || process.env.ANTHROPIC_API_KEY;
  } else if (provider === 'openrouter') {
    activeKey = keys.openrouter || process.env.OPENROUTER_API_KEY;
  } else if (provider === 'ollama') {
    activeKey = keys.ollamaUrl || process.env.OLLAMA_URL || 'http://localhost:11434';
  }

  if (provider !== 'ollama' && provider !== 'gemini' && !activeKey) {
    return { success: false, error: 'API Key is missing' };
  }

  try {
    if (provider === 'gemini') {
      const ai = new GoogleGenAI({ apiKey: activeKey });
      const res = await ai.models.generateContent({
        model: providerInfo.model,
        contents: [{ role: 'user', parts: [{ text: 'Hello' }] }]
      });
      if (res.text) return { success: true };
      throw new Error("No response text");
    } 
    else {
      let headers = { 'Content-Type': 'application/json' };
      let body = {};
      const testMsg = [{ role: 'user', content: 'Hello' }];

      if (provider === 'openai') {
        headers['Authorization'] = `Bearer ${activeKey}`;
        body = { model: providerInfo.model, messages: testMsg, max_tokens: 10 };
      } 
      else if (provider === 'anthropic') {
        headers['x-api-key'] = activeKey;
        headers['anthropic-version'] = '2023-06-01';
        body = { model: providerInfo.model, messages: testMsg, max_tokens: 10 };
      }
      else if (provider === 'openrouter') {
        headers['Authorization'] = `Bearer ${activeKey}`;
        body = { model: providerInfo.model, messages: testMsg, max_tokens: 10 };
      }
      else if (provider === 'ollama') {
        try {
          const detectedModel = await getOllamaModel(activeKey, providerInfo.model);
          body = { model: detectedModel, messages: testMsg, stream: false };
        } catch (err) {
          return { success: false, error: err.message };
        }
      }

      const url = provider === 'ollama' ? `${activeKey}/api/chat` : providerInfo.endpoint;

      const response = await fetch(url, {
        method: 'POST',
        headers,
        body: JSON.stringify(body)
      });

      if (!response.ok) {
        const errText = await response.text();
        throw new Error(`HTTP ${response.status}: ${errText}`);
      }

      return { success: true };
    }
  } catch (err) {
    let errorMsg = err.message || 'Connection failed';
    if (err.cause) {
      errorMsg += ` (Exact reason: ${err.cause.message || err.cause})`;
    }
    return { success: false, error: errorMsg };
  }
});

// Orchestrate Gemini interactions and tool calling over IPC
ipcMain.on('send-chat-message', async (event, { messages, apiKey, activeProvider, customKeys }) => {
  try {
    const providerList = providersConfig.failoverOrder;
    const targetProvider = activeProvider || providersConfig.defaultProvider || 'gemini';
    const keys = customKeys || {};

    let currentProviderIndex = -1;
    let selectedProvider = targetProvider;

    // Check if target is in the list
    if (targetProvider === 'auto-failover') {
      selectedProvider = providerList[0];
      currentProviderIndex = 0;
    } else {
      currentProviderIndex = providerList.indexOf(targetProvider);
    }

    let success = false;
    let attempts = 0;
    const maxAttempts = providerList.length;

    while (!success && attempts < maxAttempts) {
      attempts++;
      const currentProvider = selectedProvider;
      event.reply('active-provider-changed', currentProvider);

      // Fetch api key and config
      const providerInfo = providersConfig.providers[currentProvider];
      if (!providerInfo) {
        // Skip unknown
        currentProviderIndex = (currentProviderIndex + 1) % providerList.length;
        selectedProvider = providerList[currentProviderIndex];
        continue;
      }

      let activeKey = '';
      if (currentProvider === 'gemini') {
        activeKey = apiKey || keys.gemini || process.env.GEMINI_API_KEY || '';
      } else if (currentProvider === 'openai') {
        activeKey = keys.openai || process.env.OPENAI_API_KEY;
      } else if (currentProvider === 'anthropic') {
        activeKey = keys.anthropic || process.env.ANTHROPIC_API_KEY;
      } else if (currentProvider === 'openrouter') {
        activeKey = keys.openrouter || process.env.OPENROUTER_API_KEY;
      } else if (currentProvider === 'ollama') {
        activeKey = keys.ollamaUrl || process.env.OLLAMA_URL || 'http://localhost:11434';
      }

      // Check if credentials are set (skip if missing, unless it's Ollama or Gemini which have defaults)
      if (currentProvider !== 'ollama' && currentProvider !== 'gemini' && !activeKey) {
        console.warn(`Skipping ${currentProvider} because API key is empty.`);
        currentProviderIndex = (currentProviderIndex + 1) % providerList.length;
        selectedProvider = providerList[currentProviderIndex];
        continue;
      }

      console.log(`Attempting chat with provider: ${currentProvider} (Model: ${providerInfo.model})...`);

try {
        if (currentProvider === 'gemini') {
          const ai = new GoogleGenAI({ apiKey: activeKey });
          const contents = messages.map(msg => ({
            role: msg.role === 'assistant' ? 'model' : 'user',
            parts: [{ text: msg.content }]
          }));

          let sessionContents = [...contents];
          let loopLimit = 5; 
          let runLoop = true;

          while (runLoop && loopLimit > 0) {
            loopLimit--;
            const responseStream = await ai.models.generateContentStream({
              model: providerInfo.model,
              contents: sessionContents,
              config: {
                tools: [{ functionDeclarations: sharedTools }],
                systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] }
              }
            });

            let isFunctionCall = false;
            let functionCall = null;
            let responseParts = [];

            for await (const chunk of responseStream) {
              const candidate = chunk.candidates?.[0];
              if (candidate?.content?.parts) {
                responseParts.push(...candidate.content.parts);
              }
              if (chunk.functionCalls && chunk.functionCalls.length > 0) {
                isFunctionCall = true;
                functionCall = chunk.functionCalls[0];
              }
              try {
                if (chunk.text) {
                  event.reply('chat-chunk', chunk.text);
                }
              } catch (e) {
                // Ignore exception thrown by SDK when accessing chunk.text on tool call chunks
              }
            }

            if (isFunctionCall && functionCall) {
              const executionResult = await executeRequestedTool(functionCall.name, functionCall.args, event, keys);
              sessionContents.push({ role: 'model', parts: responseParts });
              sessionContents.push({ role: 'user', parts: [{ functionResponse: { name: functionCall.name, response: { result: executionResult } } }] });
              continue;
            }
            runLoop = false;
          }
          success = true;
        } 
        else if (currentProvider === 'openai' || currentProvider === 'openrouter') {
          let sessionMessages = [
            { role: 'system', content: SYSTEM_PROMPT },
            ...messages.map(m => ({ role: m.role, content: m.content }))
          ];

          let loopLimit = 5;
          let runLoop = true;

          while (runLoop && loopLimit > 0) {
            loopLimit--;
            let headers = {
              'Content-Type': 'application/json',
              'Authorization': `Bearer ${activeKey}`
            };
            if (currentProvider === 'openrouter') {
              headers['HTTP-Referer'] = 'http://localhost:5173';
              headers['X-Title'] = 'Edu AI Desktop';
            }

            const response = await fetch(providerInfo.endpoint, {
              method: 'POST',
              headers,
              body: JSON.stringify({
                model: providerInfo.model,
                messages: sessionMessages,
                tools: openaiTools,
                stream: true
              })
            });

            if (!response.ok) {
              throw new Error(`HTTP ${response.status}: ${await response.text()}`);
            }

            let functionCallName = "";
            let functionCallArgs = "";
            let isFunctionCall = false;

            const reader = response.body;
            for await (const chunk of reader) {
              const text = chunk.toString();
              const lines = text.split('\n');
              for (const line of lines) {
                const cleanLine = line.trim();
                if (cleanLine.startsWith('data: ') && cleanLine !== 'data: [DONE]') {
                  try {
                    const parsed = JSON.parse(cleanLine.substring(6));
                    const delta = parsed.choices?.[0]?.delta;
                    
                    if (delta?.content) {
                      event.reply('chat-chunk', delta.content);
                    }
                    if (delta?.tool_calls) {
                      isFunctionCall = true;
                      if (delta.tool_calls[0].function?.name) {
                        functionCallName = delta.tool_calls[0].function.name;
                      }
                      if (delta.tool_calls[0].function?.arguments) {
                        functionCallArgs += delta.tool_calls[0].function.arguments;
                      }
                    }
                  } catch (e) {}
                }
              }
            }

            if (isFunctionCall && functionCallName) {
              let parsedArgs = {};
              try { parsedArgs = JSON.parse(functionCallArgs); } catch (e) { console.error("Failed to parse tool args", e); }
              const executionResult = await executeRequestedTool(functionCallName, parsedArgs, event, keys);
              
              sessionMessages.push({
                role: 'assistant',
                content: null,
                tool_calls: [{
                  id: `call_${Date.now()}`,
                  type: 'function',
                  function: { name: functionCallName, arguments: functionCallArgs }
                }]
              });
              sessionMessages.push({
                role: 'tool',
                tool_call_id: sessionMessages[sessionMessages.length - 1].tool_calls[0].id,
                name: functionCallName,
                content: executionResult
              });
              continue;
            }
            runLoop = false;
          }
          success = true;
        }
        else if (currentProvider === 'anthropic') {
          let sessionMessages = messages.map(m => ({ role: m.role, content: m.content }));
          
          let loopLimit = 5;
          let runLoop = true;

          while (runLoop && loopLimit > 0) {
            loopLimit--;
            const response = await fetch(providerInfo.endpoint, {
              method: 'POST',
              headers: {
                'Content-Type': 'application/json',
                'x-api-key': activeKey,
                'anthropic-version': '2023-06-01'
              },
              body: JSON.stringify({
                model: providerInfo.model,
                system: SYSTEM_PROMPT,
                messages: sessionMessages,
                tools: anthropicTools,
                max_tokens: 4096,
                stream: true
              })
            });

            if (!response.ok) {
              throw new Error(`HTTP ${response.status}: ${await response.text()}`);
            }

            let functionCallName = "";
            let functionCallArgs = "";
            let toolUseId = "";
            let isFunctionCall = false;

            const reader = response.body;
            for await (const chunk of reader) {
              const text = chunk.toString();
              const lines = text.split('\n');
              for (const line of lines) {
                const cleanLine = line.trim();
                if (cleanLine.startsWith('data: ')) {
                  try {
                    const parsed = JSON.parse(cleanLine.substring(6));
                    if (parsed.type === 'content_block_delta' && parsed.delta?.text) {
                      event.reply('chat-chunk', parsed.delta.text);
                    }
                    else if (parsed.type === 'content_block_start' && parsed.content_block?.type === 'tool_use') {
                      isFunctionCall = true;
                      functionCallName = parsed.content_block.name;
                      toolUseId = parsed.content_block.id;
                    }
                    else if (parsed.type === 'content_block_delta' && parsed.delta?.type === 'input_json_delta') {
                      functionCallArgs += parsed.delta.partial_json;
                    }
                  } catch (e) {}
                }
              }
            }

            if (isFunctionCall && functionCallName) {
              let parsedArgs = {};
              try { parsedArgs = JSON.parse(functionCallArgs); } catch (e) { console.error("Failed to parse tool args", e); }
              const executionResult = await executeRequestedTool(functionCallName, parsedArgs, event, keys);
              
              sessionMessages.push({
                role: 'assistant',
                content: [
                  { type: 'tool_use', id: toolUseId, name: functionCallName, input: parsedArgs }
                ]
              });
              sessionMessages.push({
                role: 'user',
                content: [
                  { type: 'tool_result', tool_use_id: toolUseId, content: executionResult }
                ]
              });
              continue;
            }
            runLoop = false;
          }
          success = true;
        }
        else {
          // OLLAMA (No tool support in this simple implementation)
          const detectedModel = await getOllamaModel(activeKey, providerInfo.model);
          const ollamaUrl = activeKey.endsWith('/api/chat') ? activeKey : `${activeKey}/api/chat`;
          event.reply('chat-chunk', `\n\n*[Ollama: Connecting to local model (${detectedModel})...]*\n\n`);
          const response = await fetch(ollamaUrl, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              model: detectedModel,
              messages: [
                { role: 'system', content: SYSTEM_PROMPT },
                ...messages.map(m => ({ role: m.role, content: m.content }))
              ],
              stream: true
            })
          });
          if (!response.ok) throw new Error(`HTTP ${response.status}: ${await response.text()}`);
          await handleSSEStream(response, currentProvider, event);
          success = true;
        }
      } catch (err) {
        console.error(`Error on provider ${currentProvider}:`, err.message || err);
        // If user explicitly chose this provider and did not ask for auto-failover,
        // we ONLY failover if Gemini returns a 429 quota exhaustion.
        const isRateLimited = err.message && (err.message.includes('429') || err.message.includes('quota') || err.message.includes('exhausted') || err.message.includes('Quota exceeded'));
        
        if (targetProvider === 'auto-failover' || (targetProvider === 'gemini' && isRateLimited)) {
          const failMsg = `[${new Date().toISOString()}] Failed on ${currentProvider}: ${err.message || err}. Failing over to next provider.`;
          event.reply('add-failover-history', failMsg);
          event.reply('chat-chunk', `\n\n*[Rate-limited or unavailable on ${currentProvider}. Failing over to next provider...]*\n\n`);
          currentProviderIndex = (currentProviderIndex + 1) % providerList.length;
          selectedProvider = providerList[currentProviderIndex];
        } else {
          // Return error immediately if they locked it to a specific provider that failed for other reasons
          throw err;
        }
      }
    }

    if (!success) {
      throw new Error("All AI providers exhausted. Please check your internet connection and API keys.");
    }

    event.reply('chat-done');
  } catch (error) {
    console.error('Electron main process error:', error);
    let errorMsg = error.message || 'An unknown error occurred inside Electron.';
    if (error.cause) {
      errorMsg += ` (Exact reason: ${error.cause.message || error.cause})`;
    }
    event.reply('chat-error', errorMsg);
  }
});
